std::string ProgramCCodeGenerator::generate(const std::vector<unsigned char>& bytecode,
                                             const Options& options) {
  const uint32_t mem_size =
      options.memory_variables == 0 ? kDefaultMemoryVariables : options.memory_variables;
  const uint32_t stack_size =
      options.stack_capacity == 0 ? kDefaultStackCapacity : options.stack_capacity;
  const uint32_t max_steps =
      options.max_steps == 0 ? kDefaultMaxSteps : options.max_steps;

  std::string banner;
  if (!options.source_description.empty()) {
    // Wrap the description into the top comment so the generated file is self-describing.
    // The leading " *" plus space matches the surrounding comment style in the template.
    std::ostringstream b;
    std::istringstream lines(options.source_description);
    std::string line;
    while (std::getline(lines, line)) {
      b << " * " << line << "\n";
    }
    banner = b.str();
  }

  std::string out = kCRuntimeTemplate;
  substitute(out, "{{BANNER}}", banner);
  substitute(out, "{{MEM_SIZE}}", std::to_string(mem_size));
  substitute(out, "{{STACK_SIZE}}", std::to_string(stack_size));
  substitute(out, "{{MAX_STEPS}}", std::to_string(max_steps));
  substitute(out, "{{PROGRAM_BYTES}}",
             bytecode.empty() ? std::string("  0x00") : renderBytecodeArray(bytecode));
  return out;
}

