void substitute(std::string& s, const std::string& placeholder, const std::string& value) {
  // Single-pass replace-all. The template was authored so each placeholder appears
  // exactly once, but we still loop to keep this defensive against future template
  // edits that might re-use a placeholder.
  std::string::size_type pos = 0;
  while ((pos = s.find(placeholder, pos)) != std::string::npos) {
    s.replace(pos, placeholder.size(), value);
    pos += value.size();
  }
}

